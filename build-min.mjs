// build-min.js — Copia arquivos para dist/ e gera env-config.js
import fs from 'fs';
import path from 'path';

const DIST_DIR = 'dist';

// Limpa dist/
if (fs.existsSync(DIST_DIR)) fs.rmSync(DIST_DIR, { recursive: true });
fs.mkdirSync(DIST_DIR, { recursive: true });

// Copia HTMLs
['index.html','admin.html','taro2.html','login.html','dashboard.html','dna.html','numerologia.html','hawkins.html','bovis.html','cursos.html','curso-player.html','mestres.html'].forEach(f => {
    if (fs.existsSync(f)) {
        fs.mkdirSync(path.dirname(path.join(DIST_DIR,f)), { recursive: true });
        fs.copyFileSync(f, path.join(DIST_DIR,f));
        console.log('Copiado:', f);
    }
});

// Copia pastas js/ e css/
['js','css','assets'].forEach(pasta => {
    if (fs.existsSync(pasta)) {
        fs.cpSync(pasta, path.join(DIST_DIR,pasta), { recursive: true, filter: (src) => !path.basename(src).startsWith('.') && path.basename(src) !== 'node_modules' });
        console.log('Copiado pasta:', pasta);
    }
});

// Gera env-config.js com chave do .env se existir
let apiKey = '';
try { apiKey = fs.readFileSync('.env.local','utf8').match(/OPENROUTER_API_KEY=(.+)/)?.[1]?.trim() || ''; } catch(e) {}
// Fallback: pega do env-config.js local
if (!apiKey) {
    try {
        const localEnv = fs.readFileSync('js/env-config.js','utf8');
        const m = localEnv.match(/__OPENROUTER_API_KEY__\s*=\s*["']([^"']+)["']/);
        if (m) apiKey = m[1];
    } catch(e) {}
}

const envConfig = `// Generated by build-min.js
window.__SUPABASE_URL__ = "https://frvqvnusjnnmbpztiokn.supabase.co";
window.__SUPABASE_ANON_KEY__ = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImZydnF2bnVzam5ubWJwenRpb2tuIiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODg1MjE0OTUsImV4cCI6MjEwNDA5NzQ5NX0.na4JZ9CqMhCxWnK-FGPVd-urJ78LTEzGBPE0IwitVJ0";
window.__OPENROUTER_API_KEY__ = ${JSON.stringify(apiKey)};
window.__OPENROUTER_MODEL__ = "deepseek/deepseek-v4-flash-0731";
`;
fs.writeFileSync(path.join(DIST_DIR,'js','env-config.js'), envConfig);
console.log('env-config.js gerado com chave:', apiKey ? 'OK' : 'VAZIA!');

// Atualiza cachebusters nos HTMLs
['admin.html','index.html','taro2.html','login.html','dashboard.html'].forEach(f => {
    const fp = path.join(DIST_DIR,f);
    if (!fs.existsSync(fp)) return;
    let c = fs.readFileSync(fp,'utf8');
    if (!c.includes('js/env-config.js')) c = c.replace('</head>','  <script src="js/env-config.js"></script>\n</head>');
    c = c.replace(/\?v=[\d.]+/g, '?v=' + Date.now());
    fs.writeFileSync(fp,c,'utf8');
    console.log('Cachebuster atualizado:', f);
});

console.log('✅ Build concluido!');